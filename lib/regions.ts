/** Administrative merger names coexist with the official subsidy authority codes.
 * Source: https://www.mois.go.kr/frt/sub/a04/localGovernment/screen.do
 */
const mergedProvinceName = "전남광주통합특별시";
const mergedAuthorities = regions.filter(r => !r.children?.length && (r.province === "전라남도" || r.id === "2900"));
for (const authority of mergedAuthorities) {
  const names = authority.id === "2900" ? [authority.name, "동구", "서구", "남구", "북구", "광산구"] : [authority.name];
  for (const prefix of [mergedProvinceName, "전남광주", "광주전남"]) {
    for (const name of names) authority.aliases.push(`${prefix} ${name}`);
  }
}
regions.push({id:`province:${mergedProvinceName}`,province:mergedProvinceName,name:mergedProvinceName,aliases:["전남광주", "광주전남", "광주전남통합특별시"],children:mergedAuthorities.map(r=>r.id)});

/** Compact queries while preserving geography, including common province aliases. */
export function normalizeRegionQuery(value: string): string {
  return value.normalize("NFKC")
    .replace(/서울특별시|서울시/g, "서울")
    .replace(/부산광역시|부산시/g, "부산")
    .replace(/대구광역시|대구시/g, "대구")
    .replace(/인천광역시|인천시/g, "인천")
    .replace(/광주광역시/g, "광주")
    .replace(/대전광역시|대전시/g, "대전")
    .replace(/울산광역시|울산시/g, "울산")
    .replace(/세종특별자치시|세종시/g, "세종")
    .replace(/강원특별자치도|강원도/g, "강원")
    .replace(/전북특별자치도|전라북도|전북도/g, "전북")
    .replace(/제주특별자치도|제주도/g, "제주")
    .replace(/충청북도|충북도/g, "충북")
    .replace(/충청남도|충남도/g, "충남")
    .replace(/전라남도|전남도/g, "전남")
    .replace(/경상북도|경북도/g, "경북")
    .replace(/경상남도|경남도/g, "경남")
    .replace(/경기도/g, "경기")
    .replace(/특례시/g, "시")
    .replace(/[\s·ㆍ,./_()-]+/g, "")
    .toLowerCase();
}

/** Exact matches rank first; shared district names keep every matching authority. */
export function searchRegions(query: string, limit = 30): Region[] {
  const compact = normalizeRegionQuery(query);
  if (!compact) return [];
  return regions.map((region, index) => {
    const names = [region.name, ...region.aliases].map(normalizeRegionQuery);
    const score = names.some((name) => name === compact) ? 0
      : names.some((name) => name.startsWith(compact)) ? 1
      : names.some((name) => name.includes(compact)) ? 2 : 3;
    return { region, score, index };
  }).filter(({ score }) => score < 3)
    .sort((a, b) => a.score - b.score || a.index - b.index)
    .slice(0, limit)
    .map(({ region }) => region);
}
